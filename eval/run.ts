/**
 * OFFLINE evaluation runner — NOT part of CI.
 *
 * This script makes a REAL Gemini call (one batched request over the whole synthetic dataset),
 * scores the predictions with the pure metrics in ./metrics, and writes a human-readable
 * eval/report.md. It runs offline/on-demand because real LLM calls cost money + quota and are
 * non-deterministic — the opposite of what a fast, hermetic CI gate needs. CI stays mocked/pure;
 * this produces the artifact that tells us how good the categorizer actually is.
 *
 * Run: npm run eval   (loads .env.local for GEMINI_API_KEY via dotenv-cli, then tsx runs this)
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { categorizeTransactions, MODEL, CATEGORY_SCHEMA_VERSION } from "@/lib/categorize";
import { dataset } from "./dataset";
import { accuracy, macroF1, perCategory, confusionMatrix } from "./metrics";

// Fixed date — the categorizer's prompt ignores the date, so a constant keeps the run reproducible.
const FIXED_DATE = new Date("2024-01-01T00:00:00.000Z");

function pct(n: number): string {
  return `${(n * 100).toFixed(1)}%`;
}

function fmtUsd(n: number | undefined): string {
  return n === undefined ? "n/a" : `$${n.toFixed(6)}`;
}

function buildReport(
  predicted: string[],
  expected: string[],
  metrics: {
    latencyMs: number;
    totalTokens?: number;
    promptTokens?: number;
    candidatesTokens?: number;
    costEstimateUsd?: number;
  },
  runDate: Date,
): string {
  const perCat = perCategory(predicted, expected);
  const labels = Object.keys(perCat).sort();
  const cm = confusionMatrix(predicted, expected);
  const cmLabels = Object.keys(cm).sort();

  const perCatRows = labels
    .map((label) => {
      const m = perCat[label];
      return `| ${label} | ${pct(m.precision)} | ${pct(m.recall)} | ${pct(m.f1)} | ${m.support} |`;
    })
    .join("\n");

  // Confusion matrix: rows = actual, columns = predicted.
  const cmHeader = `| actual \\ predicted | ${cmLabels.join(" | ")} |`;
  const cmDivider = `| --- | ${cmLabels.map(() => "---").join(" | ")} |`;
  const cmRows = cmLabels
    .map((actual) => `| ${actual} | ${cmLabels.map((p) => cm[actual][p]).join(" | ")} |`)
    .join("\n");

  return `# LedgerLens — Categorization Evaluation Report

> Generated by \`npm run eval\` against a **synthetic** dataset (see eval/README.md). No real data.

- **Model:** \`${MODEL}\`
- **Category schema version:** ${CATEGORY_SCHEMA_VERSION}
- **Run date:** ${runDate.toISOString()}
- **N (transactions):** ${expected.length}

## Headline

- **Accuracy:** ${pct(accuracy(predicted, expected))}
- **Macro-F1:** ${pct(macroF1(predicted, expected))}

Accuracy is the fraction labeled correctly overall; macro-F1 is the unweighted mean of per-category
F1, so a category the model never gets right pulls it down even when accuracy stays high. Read them
together.

## Per-category precision / recall / F1

| Category | Precision | Recall | F1 | Support |
| --- | --- | --- | --- | --- |
${perCatRows}

## Confusion matrix (rows = actual, columns = predicted)

${cmHeader}
${cmDivider}
${cmRows}

The diagonal is correct; an off-diagonal cell shows which wrong category the model confused a true
label with.

## Observability (from the single batched call)

- **Latency:** ${metrics.latencyMs} ms
- **Prompt tokens:** ${metrics.promptTokens ?? "n/a"}
- **Candidates tokens:** ${metrics.candidatesTokens ?? "n/a"}
- **Total tokens:** ${metrics.totalTokens ?? "n/a"}
- **Estimated cost:** ${fmtUsd(metrics.costEstimateUsd)}
`;
}

async function main(): Promise<void> {
  const expected = dataset.map((d) => d.expectedCategory as string);

  console.info(`Evaluating ${dataset.length} synthetic transactions with ${MODEL}…`);
  const { categories, metrics } = await categorizeTransactions(
    dataset.map((d) => ({ date: FIXED_DATE, rawDescription: d.rawDescription, amount: d.amount })),
  );
  const predicted = categories as string[];

  // `new Date()` is fine here — this is a plain script, not a workflow.
  const report = buildReport(predicted, expected, metrics, new Date());

  const outPath = join(dirname(fileURLToPath(import.meta.url)), "report.md");
  await writeFile(outPath, report, "utf8");

  console.info(`Accuracy: ${pct(accuracy(predicted, expected))}  Macro-F1: ${pct(macroF1(predicted, expected))}`);
  console.info(`Report written to ${outPath}`);
}

main().catch((err) => {
  console.error("Eval run failed:", err instanceof Error ? err.message : err);
  process.exit(1);
});
